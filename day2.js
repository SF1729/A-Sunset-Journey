/**
 * Main Flow Controller: Gate 1 (Date Lock) → Gate 2 (Memory Match) → Day 2 Content
 */
function initDay2Flow() {
  const day2DateStr = "2026-10-16";
  const dateLockedView = document.getElementById("day2DateLockedView");
  const gameLockedView = document.getElementById("day2GameLockedView");
  const unlockedView = document.getElementById("day2UnlockedView");

  // Shortcut for testing (?reset=1 resets browser memory)
  const urlParams = new URLSearchParams(window.location.search);
  if (urlParams.get("reset") === "1" || urlParams.get("reset") === "true") {
    localStorage.removeItem("budduu_day2_lock_solved");
    localStorage.removeItem("budduu_day2_completed");
    isGameSolved = false;
  }

  // GATE 1: Check Date Lock (Unlocks on 21 October 2026)
  const isDateReady = typeof isDateUnlocked === "function" 
    ? isDateUnlocked(day2DateStr) 
    : (new Date().getTime() >= new Date("2026-10-21T00:00:00+05:30").getTime() || urlParams.has("previewDate"));

  if (!isDateReady) {
    if (dateLockedView) dateLockedView.style.display = "flex";
    if (gameLockedView) gameLockedView.style.display = "none";
    if (unlockedView) unlockedView.style.display = "none";

    const daysRemaining = typeof getDaysUntil === "function" ? getDaysUntil(day2DateStr) : 4;
    const countdownEl = document.getElementById("dateLockCountdown");
    if (countdownEl) {
      countdownEl.textContent = daysRemaining > 0 
        ? `Unlocks in ${daysRemaining} ${daysRemaining === 1 ? 'day' : 'days'} (21 October 2026)`
        : "Unlocks on 21 October 2026";
    }
    return;
  }

  if (dateLockedView) dateLockedView.style.display = "none";

  // Check LocalStorage
  try {
    if (localStorage.getItem("budduu_day2_lock_solved") === "true") {
      isGameSolved = true;
    }
    if (localStorage.getItem("budduu_day2_completed") === "true") {
      isGameSolved = true;
      hasViewedGallery = true;
    }
  } catch (err) {}

  initDay2Bokeh();
  initNextDayNavigation();

  // GATE 2: Memory Match Game
  if (!isGameSolved) {
    if (gameLockedView) gameLockedView.style.display = "flex";
    if (unlockedView) unlockedView.style.display = "none";
    initMemoryMatchGame();
    return;
  }

  // Unlocked
  launchActualDay2Content();
}

/**
 * Ambient Bokeh Background Canvas
 */
function initDay2Bokeh() {
  const canvas = document.getElementById("day2BokehCanvas");
  if (!canvas) return;

  const ctx = canvas.getContext("2d");
  let width = (canvas.width = window.innerWidth);
  let height = (canvas.height = window.innerHeight);

  window.addEventListener("resize", () => {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
  }, { passive: true });

  const count = window.innerWidth <= 768 ? 20 : 40;
  const particles = [];

  for (let i = 0; i < count; i++) {
    particles.push({
      x: Math.random() * width,
      y: Math.random() * height,
      radius: Math.random() * 3 + 1,
      speedY: Math.random() * 0.25 + 0.08,
      speedX: (Math.random() - 0.5) * 0.2,
      opacity: Math.random() * 0.6 + 0.2,
      pulse: Math.random() * Math.PI
    });
  }

  function render() {
    ctx.clearRect(0, 0, width, height);

    particles.forEach((p) => {
      p.y -= p.speedY;
      p.x += p.speedX;

      if (p.y < 0) {
        p.y = height;
        p.x = Math.random() * width;
      }

      p.pulse += 0.015;
      const alpha = p.opacity * (0.6 + 0.4 * Math.sin(p.pulse));

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(255, 179, 71, ${alpha})`;
      ctx.shadowBlur = 8;
      ctx.shadowColor = "rgba(255, 107, 74, 0.6)";
      ctx.fill();
    });

    requestAnimationFrame(render);
  }

  render();
}

/**
 * GATE 2: 4x4 Memory Match Game
 */
function initMemoryMatchGame() {
  const grid = document.getElementById("memoryMatchGrid");
  if (!grid) return;

  const deck = [...matchSymbols, ...matchSymbols].sort(() => Math.random() - 0.5);

  grid.innerHTML = "";
  movesCount = 0;
  matchedPairsCount = 0;
  updateStatsDisplay();

  deck.forEach((symbol, index) => {
    const card = document.createElement("div");
    card.className = "match-tile-card";
    card.dataset.symbol = symbol;
    card.setAttribute("role", "button");
    card.setAttribute("tabindex", "0");

    card.innerHTML = `
      <div class="match-tile-inner">
        <div class="match-tile-face match-tile-front">?</div>
        <div class="match-tile-face match-tile-back">${symbol}</div>
      </div>
    `;

    card.addEventListener("click", () => handleCardClick(card));
    grid.appendChild(card);
  });
}

function handleCardClick(card) {
  if (lockBoard || card === firstCard || card.classList.contains("is-matched") || card.classList.contains("is-flipped")) {
    return;
  }

  if (!hasTimerStarted) {
    hasTimerStarted = true;
    gameTimerInterval = setInterval(() => {
      gameSecondsElapsed++;
      const timerDisplay = document.getElementById("timerDisplay");
      if (timerDisplay) {
        const mins = String(Math.floor(gameSecondsElapsed / 60)).padStart(2, "0");
        const secs = String(gameSecondsElapsed % 60).padStart(2, "0");
        timerDisplay.textContent = `${mins}:${secs}`;
      }
    }, 1000);
  }

  card.classList.add("is-flipped");

  if (!firstCard) {
    firstCard = card;
    return;
  }

  secondCard = card;
  lockBoard = true;
  movesCount++;
  updateStatsDisplay();

  if (firstCard.dataset.symbol === secondCard.dataset.symbol) {
    firstCard.classList.add("is-matched");
    secondCard.classList.add("is-matched");
    matchedPairsCount++;
    updateStatsDisplay();
    firstCard = null;
    secondCard = null;
    lockBoard = false;

    if (matchedPairsCount === 8) {
      if (gameTimerInterval) clearInterval(gameTimerInterval);
      isGameSolved = true;
      try {
        localStorage.setItem("budduu_day2_lock_solved", "true");
      } catch (e) {}

      const successOverlay = document.getElementById("matchSuccessOverlay");
      if (successOverlay) successOverlay.style.display = "flex";

      setTimeout(() => {
        document.getElementById("day2GameLockedView").style.display = "none";
        launchActualDay2Content();
      }, 2200);
    }
  } else {
    setTimeout(() => {
      if (firstCard) firstCard.classList.remove("is-flipped");
      if (secondCard) secondCard.classList.remove("is-flipped");
      firstCard = null;
      secondCard = null;
      lockBoard = false;
    }, 850);
  }
}

function updateStatsDisplay() {
  const movesEl = document.getElementById("movesCountDisplay");
  const pairsEl = document.getElementById("pairsCountDisplay");
  if (movesEl) movesEl.textContent = String(movesCount).padStart(2, "0");
  if (pairsEl) pairsEl.textContent = `${matchedPairsCount} / 8`;
}

